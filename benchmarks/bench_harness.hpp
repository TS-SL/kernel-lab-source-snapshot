using Clock = std::chrono::steady_clock;

inline const char*& program_name() {
    static const char* name = "bench";
    return name;
}

[[noreturn]] inline void die(const char* what) {
    std::fprintf(stderr, "%s: %s: %s\n", program_name(), what, kl_last_error_message());
    std::exit(1);
}

#define BENCH_CUDA(expr)                                                                          \
    do {                                                                                          \
        const cudaError_t e_ = (expr);                                                            \
        if (e_ != cudaSuccess) {                                                                  \
            std::fprintf(stderr, "%s: %s failed: %s\n", kl_bench::program_name(), #expr,          \
                         cudaGetErrorString(e_));                                                 \
            std::exit(1);                                                                         \
        }                                                                                         \
    } while (0)

// The build string contains quotes (compiler flags), so text fields are
// escaped for their format: JSON strings and RFC 4180 CSV fields.
inline std::string json_escape(const std::string& s) {
    std::string o;
    for (char ch : s) {
        if (ch == '"' || ch == '\\') o += '\\';
        o += ch;
    }
    return o;
}

inline std::string csv_quote(const std::string& s) {
    std::string o = "\"";
    for (char ch : s) {
        if (ch == '"') o += '"';
        o += ch;
    }
    return o + "\"";
}

struct GpuState {
    unsigned sm_mhz = 0, mem_mhz = 0, temp_c = 0;
    int pstate = -1;
    unsigned long long reasons = 0;
};

struct Nvml {
    bool ok = false;
    nvmlDevice_t dev{};
    Nvml() { ok = nvmlInit_v2() == NVML_SUCCESS && nvmlDeviceGetHandleByIndex_v2(0, &dev) == NVML_SUCCESS; }
    ~Nvml() {
        if (ok) nvmlShutdown();
    }
    Nvml(const Nvml&) = delete;
    Nvml& operator=(const Nvml&) = delete;
    GpuState sample() const {
        GpuState g;
        if (!ok) return g;
        nvmlDeviceGetClockInfo(dev, NVML_CLOCK_SM, &g.sm_mhz);
        nvmlDeviceGetClockInfo(dev, NVML_CLOCK_MEM, &g.mem_mhz);
        nvmlTemperature_t t{};
        t.version = nvmlTemperature_v1;
        t.sensorType = NVML_TEMPERATURE_GPU;
        if (nvmlDeviceGetTemperatureV(dev, &t) == NVML_SUCCESS && t.temperature > 0) {
            g.temp_c = static_cast<unsigned>(t.temperature);
        }
        nvmlPstates_t p{};
        if (nvmlDeviceGetPerformanceState(dev, &p) == NVML_SUCCESS) g.pstate = static_cast<int>(p);
        nvmlDeviceGetCurrentClocksEventReasons(dev, &g.reasons);
        return g;
    }
    std::string driver_version() const {
        char buf[96] = {0};
        if (ok && nvmlSystemGetDriverVersion(buf, sizeof(buf)) == NVML_SUCCESS) return buf;
        return "unknown";
    }
};

struct Options {
    std::string out;
    int process = 1;
    int samples = 50;
    int warmup = 10;
    double target_ms = 1.0;
    std::string commit = "unknown";
    bool quick = false;
};

inline Options parse(int argc, char** argv) {
    Options o;
    for (int i = 1; i < argc; ++i) {
        const std::string a = argv[i];
        auto next = [&] {
            if (i + 1 >= argc) die(("missing value for " + a).c_str());
            return std::string(argv[++i]);
        };
        if (a == "--out") o.out = next();
        else if (a == "--process") o.process = std::stoi(next());
        else if (a == "--samples") o.samples = std::stoi(next());
        else if (a == "--warmup") o.warmup = std::stoi(next());
        else if (a == "--target-ms") o.target_ms = std::stod(next());
        else if (a == "--commit") o.commit = next();
        else if (a == "--quick") o.quick = true;
        else die(("unknown argument " + a).c_str());
    }
    if (o.out.empty()) die("--out is required");
    if (o.samples < 1 || o.samples > 1000 || o.warmup < 0 || o.warmup > 1000 ||
        !(o.target_ms > 0 && o.target_ms <= 5)) {
        die("out-of-range --samples/--warmup/--target-ms");
    }
    return o;
}

// rows x cols (softmax, layer norm); for GEMM rows = M, cols = N, depth = K.
struct Shape {
    std::int64_t rows, cols;
    std::int64_t depth = 0;
};

struct Context {
    FILE* csv;
    FILE* meta;  // JSON array body
    const Options* opt;
    std::string gpu;
    std::string driver;
    int cuda_driver;
    int runtime;
    std::string stamp;
    const Nvml* nvml;
    int l2_bytes;
    bool first_meta = true;
};

inline void meta_item(Context& c, const std::string& json) {
    std::fprintf(c.meta, "%s\n    %s", c.first_meta ? "" : ",", json.c_str());
    c.first_meta = false;
}

inline const char* kCsvHeader =
    "harness,process,impl,rows,cols,elements,dtype,layout,sample,batch_k,ms_per_launch,"
    "host_enqueue_ms,cache,buffers,sm_clock_mhz,mem_clock_mhz,pstate,temp_c,clock_event_reasons,"
    "gpu,driver,cuda_driver,cuda_runtime,commit,build,timestamp_utc,timing,includes_transfers,depth\n";

inline void write_row(const Context& c, const char* impl, const Shape& s, int sample, int k, double ms_per_launch,
                      double host_enqueue_ms, const char* cache, int buffers, const char* timing,
                      const char* transfers) {
    const GpuState g = c.nvml->sample();
    static const std::string build_csv = csv_quote(KL_BUILD_INFO);
    std::fprintf(c.csv,
                 "cpp,%d,%s,%lld,%lld,%lld,fp32,row_major,%d,%d,%.6f,%.6f,%s,%d,%u,%u,%d,%u,0x%llx,%s,"
                 "%s,%d,%d,%s,%s,%s,%s,%s,%lld\n",
                 c.opt->process, impl, static_cast<long long>(s.rows), static_cast<long long>(s.cols),
                 static_cast<long long>(s.rows * s.cols), sample, k, ms_per_launch, host_enqueue_ms, cache,
                 buffers, g.sm_mhz, g.mem_mhz, g.pstate, g.temp_c, g.reasons, csv_quote(c.gpu).c_str(),
                 c.driver.c_str(), c.cuda_driver, c.runtime, c.opt->commit.c_str(), build_csv.c_str(),
                 c.stamp.c_str(), timing, transfers, static_cast<long long>(s.depth));
}

// Number of input/output buffer pairs so that one rotation touches >= 4x L2.
inline int rotation_pairs(std::size_t bytes_per_matrix, int l2_bytes) {
    const auto b = static_cast<std::int64_t>(bytes_per_matrix);
    return static_cast<int>(std::max<std::int64_t>(1, (4LL * l2_bytes + 2 * b - 1) / (2 * b)));
}

// One implementation under test: enqueue a launch on buffer pair p (on the
// protocol's stream), and check the output of pair p against the reference,
// returning (worst ratio to bound, number of violations).
struct Impl {
    std::string name;
    std::function<void(int p)> launch;
    std::function<std::pair<double, long long>(int p)> check;
};

// Runs the measurement protocol for one shape. poison_outputs enqueues a
// fill of every output buffer with NaN on the stream. batch_override > 0
// replaces the bytes-based batch size (GEMM: chosen from the work).
inline void run_protocol(Context& c, const Shape& s, int pairs, cudaStream_t stream, const std::vector<Impl>& impls,
                         const std::function<void()>& poison_outputs, int batch_override = 0) {
    const int k = batch_override > 0 ? batch_override : batch_k(s.rows * s.cols, c.opt->target_ms);
    cudaEvent_t start, stop;
    BENCH_CUDA(cudaEventCreate(&start));
    BENCH_CUDA(cudaEventCreate(&stop));
    int rot = 0;
    struct BatchTime {
        double gpu_ms_per_launch;
        double host_enqueue_ms;  // whole batch
    };
    auto time_batch = [&](const Impl& impl, int batch) {
        const auto h0 = Clock::now();
        BENCH_CUDA(cudaEventRecord(start, stream));
        for (int i = 0; i < batch; ++i) impl.launch(rot++ % pairs);
        BENCH_CUDA(cudaEventRecord(stop, stream));
        const auto h1 = Clock::now();
        BENCH_CUDA(cudaEventSynchronize(stop));
        float ms = 0;
        BENCH_CUDA(cudaEventElapsedTime(&ms, start, stop));
        return BatchTime{static_cast<double>(ms) / batch, std::chrono::duration<double, std::milli>(h1 - h0).count()};
    };
    // Before each check, every output buffer is poisoned (outside any timed
    // region), so a check can only pass on output the checked implementation
    // itself just wrote; the output of the most recent launch is checked.
    auto poison_run_check = [&](const Impl& impl, const char* when) {
        poison_outputs();
        for (int p = 0; p < pairs; ++p) impl.launch(rot++ % pairs);
        BENCH_CUDA(cudaStreamSynchronize(stream));
        const auto [worst, violations] = impl.check((rot - 1) % pairs);
        char buf[320];
        std::snprintf(buf, sizeof(buf),
                      "{\"type\": \"check\", \"when\": \"%s\", \"impl\": \"%s\", \"rows\": %lld, \"cols\": %lld, "
                      "\"depth\": %lld, \"worst_ratio_to_bound\": %.4f, \"violations\": %lld}",
                      when, impl.name.c_str(), static_cast<long long>(s.rows), static_cast<long long>(s.cols),
                      static_cast<long long>(s.depth), worst, violations);
        meta_item(c, buf);
        if (violations != 0) {
            std::fprintf(stderr, "%s: %s %lldx%lld (depth %lld) output FAILS the bound (%s) - aborting\n",
                         program_name(), impl.name.c_str(), static_cast<long long>(s.rows),
                         static_cast<long long>(s.cols), static_cast<long long>(s.depth), when);
            std::exit(1);
        }
    };
    for (const Impl& impl : impls) poison_run_check(impl, "before_timing");
    // The CPU-side checks leave the GPU idle long enough to drop its clocks
    // (observed in the first measured softmax series: SM clocks down to
    // 240-555 MHz in the following samples). Re-ramp with ~300 ms of this
    // shape's own launches before warm-up.
    {
        const auto t0 = Clock::now();
        while (std::chrono::duration<double, std::milli>(Clock::now() - t0).count() < 300.0) {
            for (const Impl& impl : impls) (void)time_batch(impl, k);
        }
    }
    for (int w = 0; w < c.opt->warmup; ++w) {
        for (const Impl& impl : impls) (void)time_batch(impl, k);
    }
    // Linearity: per-launch time from batches of K and 2K; a fixed per-batch
    // cost f inflates the K result by f/K: f = 2K (t_K - t_2K).
    for (const Impl& impl : impls) {
        const double tk = time_batch(impl, k).gpu_ms_per_launch;
        const double t2k = time_batch(impl, 2 * k).gpu_ms_per_launch;
        char buf[320];
        std::snprintf(buf, sizeof(buf),
                      "{\"type\": \"linearity\", \"impl\": \"%s\", \"rows\": %lld, \"cols\": %lld, \"depth\": %lld, "
                      "\"k\": %d, \"ms_per_launch_k\": %.6f, \"ms_per_launch_2k\": %.6f, \"fixed_batch_cost_ms\": %.6f}",
                      impl.name.c_str(), static_cast<long long>(s.rows), static_cast<long long>(s.cols),
                      static_cast<long long>(s.depth), k, tk, t2k, 2.0 * k * (tk - t2k));
        meta_item(c, buf);
    }
    for (int smp = 0; smp < c.opt->samples; ++smp) {
        for (std::size_t n = 0; n < impls.size(); ++n) {
            const std::size_t i = (smp % 2 == 0) ? n : impls.size() - 1 - n;  // ABBA order
            const BatchTime t = time_batch(impls[i], k);
            write_row(c, impls[i].name.c_str(), s, smp, k, t.gpu_ms_per_launch, t.host_enqueue_ms,
                      "rotated_cold_between_launches", pairs, "cuda_events_kernel_only", "no");
        }
    }
    // After timing: a fresh (poisoned, untimed) pass of each implementation is
    // checked again, so a kernel that went wrong during the series is caught.
    for (const Impl& impl : impls) poison_run_check(impl, "after_timing_fresh_pass");
    std::fflush(c.csv);
    BENCH_CUDA(cudaEventDestroy(start));
    BENCH_CUDA(cudaEventDestroy(stop));
}

// Times a host-API call (pageable memory, per-call allocation, H2D + kernel
// + D2H) with a host steady clock.
inline void run_end_to_end(Context& c, const Shape& s, const std::string& label, const std::function<void()>& call) {
    for (int w = 0; w < c.opt->warmup; ++w) call();
    for (int smp = 0; smp < c.opt->samples; ++smp) {
        const auto t0 = Clock::now();
        call();
        const auto t1 = Clock::now();
        const double ms = std::chrono::duration<double, std::milli>(t1 - t0).count();
        write_row(c, label.c_str(), s, smp, 1, ms, ms, "n/a", 1, "host_steady_clock_end_to_end",
                  "yes_pageable_plus_alloc");
    }
    std::fflush(c.csv);
}

// Program skeleton: options, device/driver metadata, output files, a ~300 ms
// clock ramp (ramp_batch enqueues ~20 short launches and synchronizes; without
// a ramp NVML still reported the 210 MHz idle clock during the first shape in
// a dry run), then run(ctx). Fails if device memory is still held at exit.
inline int bench_main(int argc, char** argv, const char* prog, const std::function<void()>& ramp_batch,
                      const std::function<void(Context&)>& run) {
    program_name() = prog;
    const Options opt = parse(argc, argv);
    kl_device_info info{};
    if (kl_get_device_info(&info) != KL_OK) die("device info");
    int l2 = 0;
    BENCH_CUDA(cudaDeviceGetAttribute(&l2, cudaDevAttrL2CacheSize, 0));

    char stamp[32];
    const std::time_t now = std::time(nullptr);
    std::tm tm_utc{};
    gmtime_s(&tm_utc, &now);
    std::strftime(stamp, sizeof(stamp), "%Y-%m-%dT%H:%M:%SZ", &tm_utc);

    FILE* csv = nullptr;
    FILE* meta = nullptr;
    if (fopen_s(&csv, opt.out.c_str(), "w") != 0 || csv == nullptr) die("cannot open --out");
    if (fopen_s(&meta, (opt.out + ".meta.json").c_str(), "w") != 0 || meta == nullptr) die("cannot open meta");
    std::fputs(kCsvHeader, csv);
    const Nvml nvml;
    Context ctx{csv, meta, &opt, info.name, nvml.driver_version(), info.driver_version, info.runtime_version,
                stamp, &nvml, l2};
    // "stamp" equals every CSV row's timestamp_utc, so the analysis can tell
    // this sidecar from one left by an earlier run of the same name.
    std::fprintf(meta, "{\n  \"harness\": \"cpp\", \"process\": %d, \"commit\": \"%s\", \"stamp\": \"%s\", \"build\": \"%s\",\n"
                       "  \"gpu\": \"%s\", \"driver\": \"%s\", \"l2_bytes\": %d, \"nvml\": %s,\n  \"items\": [",
                 opt.process, json_escape(opt.commit).c_str(), stamp, json_escape(KL_BUILD_INFO).c_str(),
                 json_escape(info.name).c_str(), json_escape(ctx.driver).c_str(), l2, nvml.ok ? "true" : "false");

    const auto t0 = Clock::now();
    while (std::chrono::duration<double, std::milli>(Clock::now() - t0).count() < 300.0) ramp_batch();
    const GpuState g = nvml.sample();
    char buf[256];
    std::snprintf(buf, sizeof(buf),
                  "{\"type\": \"after_clock_ramp\", \"ramp_ms\": 300, \"sm_mhz\": %u, \"mem_mhz\": %u, "
                  "\"pstate\": %d, \"temp_c\": %u, \"reasons\": \"0x%llx\"}",
                  g.sm_mhz, g.mem_mhz, g.pstate, g.temp_c, g.reasons);
    meta_item(ctx, buf);
    std::fprintf(stderr, "%s: %s, driver %s, L2 %d KiB, process %d; after ramp: SM %u MHz, mem %u MHz, P%d\n", prog,
                 info.name, ctx.driver.c_str(), l2 / 1024, opt.process, g.sm_mhz, g.mem_mhz, g.pstate);

    run(ctx);

    std::fprintf(meta, "\n  ]\n}\n");
    std::fclose(meta);
    std::fclose(csv);
    if (kl_device_live_bytes() != 0) {
        std::fprintf(stderr, "%s: device memory still held at exit\n", prog);
        return 1;
    }
    return 0;
}

