// Shared C++ benchmark harness (protocol: docs/methodology.md section 2),
// used by bench_softmax.cpp and bench_layernorm.cpp so both operators are
// measured with exactly the same procedure:
//
//  * Kernel time: CUDA events on one stream around a batch of K launches,
//    divided by K. K is fixed per shape (bench_common.hpp), identical for all
//    implementations of a shape (and for the Python harnesses).
//  * Cache: each shape rotates through enough input/output buffer pairs to
//    touch >= 4x L2 between reuses of a pair ("cold between launches"; for
//    matrices <= 2 MiB, re-reads within one launch can still hit L2).
//  * Interleaving: implementations alternate sample by sample, order
//    reversed every other sample (ABBA).
//  * Per batch: host enqueue time (to detect host-bound launches) and NVML
//    SM clock, memory clock, P-state, temperature, clock-event reasons
//    (read-only queries; driver-sampled, so treat them as series-level).
//  * Linearity check per implementation/shape: B(2K) vs 2 B(K) estimates any
//    fixed per-batch cost.
//  * Correctness: before timing and again after the timed series, every
//    output buffer is poisoned and one untimed pass of the implementation is
//    checked against the double reference with the tested bound.
//  * A JSON sidecar (<out>.meta.json) keeps ramp clocks, checks, linearity
//    and driver details.
