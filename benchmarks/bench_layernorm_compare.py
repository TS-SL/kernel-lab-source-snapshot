"""In-process comparison of KernelLens layer norm with PyTorch.

Same protocol as bench_softmax_compare.py (bench_protocol.py): one process,
one stream, ABBA interleaving, the same K and CUDA events for every
implementation.

PyTorch call: torch.nn.functional.layer_norm(x, (cols,), gamma, beta, eps)
under torch.no_grad(). It launches one kernel (vectorized_layer_norm_kernel
for the shapes profiled during development) that also writes the per-row
mean and rstd (8 bytes per row). aten.native_layer_norm.out was rejected:
it is an autogenerated out= variant that runs the functional op and then
copies all three outputs (3 extra device-to-device copies per call,
observed with the torch profiler). The functional call returns a new tensor
from the caching allocator; results are kept in a ring of `pairs` slots so
output memory rotates like the KernelLens outputs. Before each correctness
check, the ring is released and NaN-filled blocks of the output size are
handed back to the allocator; the sidecar records whether the checked torch
output occupied one of them (a fresh write). Which kernels torch launches
for each shape is recorded in the sidecar by the torch profiler, after all
timed shapes (so the profiler cannot affect the timing), together with the
host cost of one rows = 0 call for each side.

Usage: python benchmarks/bench_layernorm_compare.py --out FILE.csv [--process N]
       [--samples N] [--warmup N] [--target-ms X] [--commit SHA] [--quick]
"""

from __future__ import annotations

import ctypes
import sys
import time
from pathlib import Path

import torch
from torch.profiler import ProfilerActivity, profile

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tests" / "python"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import bench_protocol as bp  # noqa: E402
import kl  # noqa: E402

EPS = 1e-5
# Same shapes as bench_layernorm.cpp (pre-registered in docs/layernorm.md).
SHAPES = [(4096, 32), (4096, 128), (4096, 512), (4096, 1024), (8192, 768),
          (2048, 2048), (1024, 4096), (512, 8192), (256, 16384), (128, 32768),
          (64, 65536), (16, 262144), (4, 1048576), (4096, 4096), (2048, 8192),
          (4, 65536), (8, 65536), (16, 65536), (28, 65536), (56, 65536), (112, 65536), (224, 65536)]
QUICK_SHAPES = [(4096, 128), (1024, 4096)]


def torch_kernels(fn) -> list[str]:
    """Names of the CUDA kernels/copies one call of fn launches."""
    with profile(activities=[ProfilerActivity.CUDA]) as prof:
        fn()
        torch.cuda.synchronize()
    return sorted({e.name for e in prof.events() if e.device_type == torch.autograd.DeviceType.CUDA})


def bench_shape(run: bp.Run, lib, rows: int, cols: int, l2_bytes: int) -> None:
    # Release cached blocks of earlier shapes, so the only free blocks of this
    # shape's output size are the NaN-filled ones poison() hands back.
    torch.cuda.empty_cache()
    elems = rows * cols
    pairs = bp.rotation_pairs(elems, l2_bytes)
    host_x, xs, ys = [], [], []
    for p in range(pairs):
        h = kl.fill_uniform(1000 + 31 * p + cols, elems, -10.0, 10.0).reshape(rows, cols)
        host_x.append(h)
        xs.append(torch.from_numpy(h).cuda())
        ys.append(torch.empty_like(xs[-1]))
    host_g = kl.fill_uniform(5000 + cols, cols, 0.5, 1.5)
    host_b = kl.fill_uniform(6000 + cols, cols, -1.0, 1.0)
    g, b = torch.from_numpy(host_g).cuda(), torch.from_numpy(host_b).cuda()
    ws = torch.empty(max(1, 2 * rows), device="cuda")  # MULTIPASS workspace (2 floats per row)
    handle = ctypes.c_void_p(run.stream.cuda_stream)
    torch_out = [None] * pairs  # ring of torch results (see module docstring)
    poisoned = set()  # device addresses of NaN-filled blocks handed to the allocator

    def kl_launch(impl):
        def launch(p):
            st = lib.kl_layernorm_device(rows, cols, xs[p].data_ptr(), g.data_ptr(), b.data_ptr(), EPS,
                                         ys[p].data_ptr(), impl, ws.data_ptr(), handle)
            if st != kl.KL_OK:
                raise RuntimeError(f"kl_layernorm_device failed: {lib.kl_last_error_message()!r}")
        return launch

    def torch_launch(p):
        torch_out[p] = torch.nn.functional.layer_norm(xs[p], (cols,), g, b, EPS)

    impls = {name: kl_launch(kl.LAYERNORM_IMPLS[name]) for name in ("multipass", "fused_block")}
    if cols <= kl.LAYERNORM_SMEM_MAX_COLS:
        impls["fused_smem"] = kl_launch(kl.LAYERNORM_FUSED_SMEM)
    if cols <= kl.LAYERNORM_WARP_MAX_COLS:
        impls["fused_warp"] = kl_launch(kl.LAYERNORM_FUSED_WARP)
    impls["torch_layer_norm"] = torch_launch

    def check(name, p):
        if name == "torch_layer_norm":
            t = torch_out[p]
            y = t.cpu().numpy()
            ref = kl.layernorm_reference(host_x[p], host_g, host_b, EPS)["y"]
            # Reported against KernelLens's FUSED_BLOCK bound for information
            # only (torch uses Welford and its own reduction order); a loose
            # sanity limit aborts the series if the baseline is broken.
            ratio = float((abs(y - ref) / kl.layernorm_allowed(host_x[p], host_g, host_b, EPS,
                                                                kl.LAYERNORM_FUSED_BLOCK)).max())
            if not ratio <= 10.0:
                raise AssertionError(f"torch_layer_norm sanity check failed: {ratio:.3g} x the fused_block bound")
            return {"max_abs_err_vs_float64": float(abs(y - ref).max()), "max_ratio_to_fused_block_bound": ratio,
                    # True when the checked tensor occupies a block poison() had filled with NaN,
                    # i.e. the values were written by this torch call.
                    "fresh_write_verified": t.data_ptr() in poisoned}
        y = ys[p].cpu().numpy()
        return {"worst_ratio_to_bound": kl.layernorm_check(host_x[p], host_g, host_b, EPS, y,
                                                           kl.LAYERNORM_IMPLS[name])}  # asserts

    def poison():
        # Runs on run.stream (inside poison_run_check). KernelLens outputs are
        # filled with NaN. torch allocates its outputs: the ring is released and
        # pairs + 1 NaN-filled blocks of the output size are handed back to the
        # caching allocator, which the next torch calls then reuse.
        for y in ys:
            y.fill_(float("nan"))
        for i in range(pairs):
            torch_out[i] = None
        blocks = [torch.full((rows, cols), float("nan"), device="cuda") for _ in range(pairs + 1)]
        poisoned.clear()
        poisoned.update(t.data_ptr() for t in blocks)
        del blocks

    with torch.no_grad():
        bp.run_protocol(run, rows, cols, pairs, impls, check, poison)


def host_dispatch_us(lib, n=2000):
    """Host cost of one call with rows = 0 (validated, returns before any
    launch), for the ctypes path and for torch on an empty tensor."""
    x = torch.zeros(0, 64, device="cuda")
    t0 = time.perf_counter()
    for _ in range(n):
        lib.kl_layernorm_device(0, 64, x.data_ptr(), None, None, EPS, x.data_ptr(), 0, None, None)
    t1 = time.perf_counter()
    with torch.no_grad():
        for _ in range(n):
            torch.nn.functional.layer_norm(x, (64,), None, None, EPS)
    torch.cuda.synchronize()
    t2 = time.perf_counter()
    return {"type": "host_dispatch_us", "kernellens_device_rows0": (t1 - t0) / n * 1e6,
            "torch_layer_norm_empty": (t2 - t1) / n * 1e6}


def main():
    lib = kl.load_library()
    ramp_bufs = {"x": torch.zeros(4096, 1024, device="cuda")}

    def ramp():
        with torch.no_grad():
            for _ in range(20):
                torch.nn.functional.layer_norm(ramp_bufs["x"], (1024,), None, None, EPS)

    def body(run, l2_bytes):
        ramp_bufs.clear()  # release the ramp tensor before measuring
        shapes = QUICK_SHAPES if run.args.quick else SHAPES
        for rows, cols in shapes:
            bench_shape(run, lib, rows, cols, l2_bytes)
        # After every timed shape (the profiler attaches to the process and
        # must not affect timing): which kernels torch launches per shape.
        with torch.no_grad():
            for rows, cols in shapes:
                x = torch.zeros(rows, cols, device="cuda")
                g, b = torch.ones(cols, device="cuda"), torch.zeros(cols, device="cuda")
                torch.nn.functional.layer_norm(x, (cols,), g, b, EPS)
                run.items.append({"type": "torch_kernels", "rows": rows, "cols": cols, "kernels": torch_kernels(
                    lambda: torch.nn.functional.layer_norm(x, (cols,), g, b, EPS))})
                del x
        run.items.append(host_dispatch_us(lib))

    bp.main(__doc__, "bench_layernorm_compare", lib, ramp, body)


if __name__ == "__main__":
    main()
