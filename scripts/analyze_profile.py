"""Summarize the Nsight Compute profile (docs/profiling.md).

Reads results/raw/<name>-ncu-raw.csv (ncu --csv --page raw output of
scripts/run-profile.ps1) and writes results/processed/<name>-profile-summary.md:
one row of key metrics per profiled launch, and the verdicts for H1-H4 with
the numeric rules of docs/profiling.md. Values are Nsight Compute counter
readings (MEASURED by the profiler; durations under profiling are not
comparable with the benchmarks' event timings).

Usage: python scripts/analyze_profile.py [--name m5]
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Launch order of benchmarks/profile_kernels.cpp: (label, operator elements for B/element).
LAUNCHES = [("softmax multipass row_max 4x65536", 4 * 65536), ("softmax multipass row_sum 4x65536", 4 * 65536),
            ("softmax multipass normalize 4x65536", 4 * 65536), ("softmax fused_online 4x65536", 4 * 65536)]
for cols in (2048, 4096, 8192):
    n = 1 << 22
    LAUNCHES += [(f"layernorm fused_block {n // cols}x{cols}", n), (f"layernorm fused_block_maxsmem {n // cols}x{cols}", n),
                 (f"layernorm fused_smem {n // cols}x{cols}", n)]
LAUNCHES += [("gemm naive 1024^3", 1024 * 1024), ("gemm naive_l2only 1024^3", 1024 * 1024),
             ("gemm tiled 1024^3", 1024 * 1024), ("gemm regblock 1024^3", 1024 * 1024),
             ("gemm cuBLAS 1024^3", 1024 * 1024)]

STALLS = ["barrier", "branch_resolving", "dispatch_stall", "drain", "imc_miss", "lg_throttle", "long_scoreboard",
          "math_pipe_throttle", "membar", "mio_throttle", "misc", "no_instructions", "not_selected",
          "short_scoreboard", "sleeping", "tex_throttle", "wait"]
DEPENDENCY = {"short_scoreboard", "long_scoreboard", "wait"}
LOAD_RELATED = {"mio_throttle", "short_scoreboard", "long_scoreboard", "lg_throttle"}
THROTTLE = {"lg_throttle", "mio_throttle"}


def num(v: str) -> float:
    v = v.replace(",", "").strip()
    return float(v) if v not in ("", "n/a") else float("nan")


def load(name):
    lines = (ROOT / "results" / "raw" / f"{name}-ncu-raw.csv").read_text(encoding="utf-8-sig").splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith('"ID"'))
    rows = list(csv.reader(lines[start:]))
    # Keep only kernel rows (the guard's closing log line also lands in the file).
    hdr, units, data = rows[0], rows[1], [r for r in rows[2:] if r and r[0].isdigit()]
    return hdr, units, [dict(zip(hdr, r)) for r in data]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", default="latest")
    args = ap.parse_args(argv)
    hdr, units, data = load(args.name)
    if len(data) != len(LAUNCHES):
        raise SystemExit(f"expected {len(LAUNCHES)} profiled launches, found {len(data)}")
    rec = {}
    for (label, elements), r in zip(LAUNCHES, data):
        stalls = {s: num(r.get(f"smsp__pcsamp_warps_issue_stalled_{s}", "")) for s in STALLS}
        total = sum(v for v in stalls.values() if v == v) or 1.0
        top = sorted(((v / total, s) for s, v in stalls.items() if v == v), reverse=True)
        rec[label] = {
            "kernel": r["Kernel Name"].split("(")[0].replace("kl::<unnamed>::", "").replace("void ", ""),
            "dram_read_per_el": num(r["dram__bytes_read.sum"]) / elements,
            "dram_write_per_el": num(r["dram__bytes_write.sum"]) / elements,
            "dram_pct": num(r["gpu__dram_throughput.avg.pct_of_peak_sustained_elapsed"]),
            "sm_pct": num(r["sm__throughput.avg.pct_of_peak_sustained_elapsed"]),
            "l1_hit": num(r["l1tex__t_sector_hit_rate.pct"]),
            "l2_hit": num(r["lts__t_sector_hit_rate.pct"]),
            "occ": num(r["sm__warps_active.avg.pct_of_peak_sustained_active"]),
            "fma": num(r["sm__inst_executed_pipe_fma.avg.pct_of_peak_sustained_active"]),
            "shared_pct": num(r.get("l1tex__data_pipe_lsu_wavefronts_mem_shared.sum.pct_of_peak_sustained_elapsed", "")),
            "top": top[:3],
            "dominant": top[0][1] if top else "n/a",
        }
    # Units of dram__bytes_read.sum (ncu may report Kbyte/Mbyte): scale to bytes.
    unit = units[hdr.index("dram__bytes_read.sum")]
    scale = {"byte": 1, "Kbyte": 1e3, "Mbyte": 1e6, "Gbyte": 1e9}.get(unit, None)
    if scale is None:
        raise SystemExit(f"unexpected unit for dram__bytes_read.sum: {unit!r}")
    unit_w = units[hdr.index("dram__bytes_write.sum")]
    scale_w = {"byte": 1, "Kbyte": 1e3, "Mbyte": 1e6, "Gbyte": 1e9}[unit_w]
    for v in rec.values():
        v["dram_read_per_el"] *= scale
        v["dram_write_per_el"] *= scale_w

    L = [f"# Nsight Compute profile summary ({args.name})", "",
         "Generated by `scripts/analyze_profile.py` from "
         f"`results/raw/{args.name}-ncu-raw.csv` (Nsight Compute, `--set detailed`, `--clock-control none`, "
         "`--cache-control all`; one profiled launch per row, in the launch order of "
         "`benchmarks/profile_kernels.cpp`). Counter values (MEASURED by the profiler). B/el = DRAM bytes per "
         "element of the operator's matrix (softmax / layer norm: the input; GEMM: per element of C).", "",
         "| launch | kernel | DRAM read B/el | DRAM write B/el | DRAM % peak | SM % peak | L1 hit % | L2 hit % | "
         "achieved occupancy % | FMA pipe % | shared-mem pipe % | top stalls (share of samples) |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for label, v in rec.items():
        tops = ", ".join(f"{s} {f:.0%}" for f, s in v["top"])
        L.append(f"| {label} | `{v['kernel']}` | {v['dram_read_per_el']:.2f} | {v['dram_write_per_el']:.2f} | "
                 f"{v['dram_pct']:.1f} | {v['sm_pct']:.1f} | {v['l1_hit']:.1f} | {v['l2_hit']:.1f} | {v['occ']:.1f} | "
                 f"{v['fma']:.1f} | {v['shared_pct']:.1f} | {tops} |")

    def verdict(supported, refuted):
        return "SUPPORTED" if supported else ("REFUTED" if refuted else "INCONCLUSIVE")

    on = rec["softmax fused_online 4x65536"]
    mp = [rec[k] for k in rec if k.startswith("softmax multipass")]
    mp_dram = sum(v["dram_pct"] for v in mp) / len(mp)
    h1 = verdict(on["dominant"] in DEPENDENCY and on["dram_pct"] < mp_dram,
                 on["dominant"] in THROTTLE or on["dram_pct"] >= mp_dram)
    fb = {c: rec[f"layernorm fused_block {(1 << 22) // c}x{c}"] for c in (2048, 4096, 8192)}
    fs = {c: rec[f"layernorm fused_smem {(1 << 22) // c}x{c}"] for c in (2048, 4096, 8192)}
    h2 = verdict(fb[2048]["dram_read_per_el"] <= 6 and fb[8192]["dram_read_per_el"] >= 9 and
                 fb[2048]["l1_hit"] >= 10 and fb[4096]["l1_hit"] >= 10 and
                 all(fs[c]["dram_read_per_el"] <= 6 for c in fs),
                 fb[2048]["dram_read_per_el"] >= 9 or (fb[2048]["l1_hit"] < 10 and fb[4096]["l1_hit"] < 10))
    smem_reads = " / ".join(format(fs[c]["dram_read_per_el"], ".2f") for c in fs)
    nv, td = rec["gemm naive 1024^3"], rec["gemm tiled 1024^3"]
    h3 = verdict(nv["dram_pct"] < 30 and td["dram_pct"] < 30 and nv["dominant"] in LOAD_RELATED and
                 td["dominant"] in LOAD_RELATED and td["occ"] <= 50,
                 nv["dram_pct"] >= 70 or td["dram_pct"] >= 70 or nv["dominant"] not in LOAD_RELATED or
                 td["dominant"] not in LOAD_RELATED)
    rb, cb = rec["gemm regblock 1024^3"], rec["gemm cuBLAS 1024^3"]
    h4 = verdict(td["fma"] < rb["fma"] < cb["fma"] and rb["dram_pct"] < 70, rb["dram_pct"] >= 70)
    L += ["", "## Hypotheses (rules in docs/profiling.md)", "",
          "| hypothesis | evidence | verdict |", "|---|---|---|",
          f"| H1 softmax online latency-bound at 4 x 65536 | dominant stall {on['dominant']}; DRAM {on['dram_pct']:.1f} % "
          f"vs multipass mean {mp_dram:.1f} % | {h1} |",
          f"| H2 fused_block re-reads cached at 2048, DRAM at 8192; fused_smem one read | fused_block DRAM read "
          f"{fb[2048]['dram_read_per_el']:.2f} / {fb[4096]['dram_read_per_el']:.2f} / {fb[8192]['dram_read_per_el']:.2f} B/el "
          f"at 2048 / 4096 / 8192 cols, L1 hit {fb[2048]['l1_hit']:.1f} / {fb[4096]['l1_hit']:.1f} %; fused_smem "
          f"{smem_reads} B/el | {h2} |",
          f"| H3 naive and tiled load-issue bound, not DRAM | DRAM {nv['dram_pct']:.1f} / {td['dram_pct']:.1f} %; "
          f"dominant stalls {nv['dominant']} / {td['dominant']}; tiled occupancy {td['occ']:.1f} % | {h3} |",
          f"| H4 regblock between tiled and cuBLAS in FMA-pipe use, not DRAM-bound | FMA pipe tiled {td['fma']:.1f} / "
          f"regblock {rb['fma']:.1f} / cuBLAS {cb['fma']:.1f} %; regblock DRAM {rb['dram_pct']:.1f} % | {h4} |"]
    out = ROOT / "results" / "processed" / f"{args.name}-profile-summary.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")
    for line in L[-4:]:
        print(line)


if __name__ == "__main__":
    main()
